#!/usr/bin/env bash
# Contrat du harness pi, repris de pi-config, sous home temporaire.

set -euo pipefail

# shellcheck source=tests/test-lib.sh
source "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/test-lib.sh"

new_test_home
trap cleanup_test_home EXIT

fail() {
  printf 'FAIL: %s\n' "$1" >&2
  exit 1
}

source_settings="$TEST_ROOT/harnesses/pi/settings.json"
pi_dir="$HOME/.pi/agent"
agents="$pi_dir/AGENTS.md"
settings="$pi_dir/settings.json"
manifest="$pi_dir/.agent-config-managed.json"
legacy_manifest="$pi_dir/.pi-config-managed.json"
ext="$pi_dir/extensions"

# --dry-run sur un home vide n'ecrit rien.
"$TEST_ROOT/install.sh" --only pi --dry-run >"$TEST_TMP/dry-empty.out"
assert_home_untouched "$HOME"
grep -q "^WOULD WRITE $settings$" "$TEST_TMP/dry-empty.out" || fail "--dry-run n'annonce pas settings.json"

# Cles ecrites par pi : elles doivent survivre a l'installation.
mkdir -p "$pi_dir"
printf '%s\n' '{"deviceId":"abc","defaultModel":"old","packages":["npm:manuel"]}' >"$settings"

if "$TEST_ROOT/install.sh" --only pi --check >"$TEST_TMP/check-before.out" 2>&1; then
  fail "--check doit echouer avant installation"
fi
grep -q "^DRIFT pi $settings content$" "$TEST_TMP/check-before.out" || fail "derive settings.json non signalee"

"$TEST_ROOT/install.sh" --only pi >"$TEST_TMP/install.out"
grep -q "^WRITE $settings$" "$TEST_TMP/install.out" || fail "WRITE settings.json absent"
grep -q "^BACKUP $settings " "$TEST_TMP/install.out" || fail "BACKUP settings.json absent"

grep -q '^<!-- Generated by agent-config; edit instructions/common.md or the harness overlay\. -->$' "$agents" ||
  fail "bandeau genere absent"
grep -q 'Tutoyer Cyril' "$agents" || fail "socle commun absent"
grep -q '^## Pi' "$agents" || fail "overlay pi absent"
[ "$(jq -r .deviceId "$settings")" = abc ] || fail "cle runtime deviceId perdue"
[ "$(jq -r .defaultModel "$settings")" = "$(jq -r .defaultModel "$source_settings")" ] ||
  fail "defaultModel source non applique"
[ "$(jq -c .packages "$settings")" = "$(jq -c .packages "$source_settings")" ] ||
  fail "packages doit etre source-owned"
[ "$(path_mode "$settings")" = 600 ] || fail "settings.json doit etre en 0600"
ls "$pi_dir"/backups/*/settings.json >/dev/null 2>&1 || fail "settings.json non sauvegarde"
[ "$(cat "$manifest")" = "$(jq -c keys "$source_settings")" ] || fail "manifeste des cles gerees"

# pi lit le hub de skills directement.
assert_link_to "$HOME/.agents/skills/api-design" "$TEST_ROOT/shared/skills/api-design"

"$TEST_ROOT/install.sh" --only pi --check >/dev/null || fail "--check doit passer apres installation"

# Reordonnancement par l'application : pas une derive.
jq 'to_entries | reverse | from_entries' "$settings" >"$TEST_TMP/reordered"
cat "$TEST_TMP/reordered" >"$settings"
"$TEST_ROOT/install.sh" --only pi --check >/dev/null || fail "--check doit ignorer l'ordre des cles"

# Extensions : vraies copies ; un tiers d'un autre nom est preserve.
for source in "$TEST_ROOT/harnesses/pi/extensions/"*.ts; do
  [ ! -L "$ext/${source##*/}" ] || fail "extension deployee en lien : ${source##*/}"
  cmp -s "$source" "$ext/${source##*/}" || fail "extension non deployee : ${source##*/}"
done
printf '%s\n' '// tiers' >"$ext/autre.ts"
"$TEST_ROOT/install.sh" --only pi --check >/dev/null || fail "une extension tierce n'est pas une derive"
printf '%s\n' '// modifie' >>"$ext/claude-clean-home.ts"
if "$TEST_ROOT/install.sh" --only pi --check >"$TEST_TMP/check-ext.out" 2>&1; then
  fail "--check doit detecter une extension modifiee"
fi
grep -q "^DRIFT pi $ext/claude-clean-home.ts content$" "$TEST_TMP/check-ext.out" || fail "derive d'extension mal signalee"
"$TEST_ROOT/install.sh" --only pi >/dev/null
cmp -s "$TEST_ROOT/harnesses/pi/extensions/claude-clean-home.ts" "$ext/claude-clean-home.ts" ||
  fail "extension modifiee non restauree"
[ -f "$ext/autre.ts" ] || fail "extension tierce supprimee"

# --dry-run sur une derive : annonce, ne modifie rien.
printf '%s\n' derive >>"$agents"
before="$(tree_fingerprint "$HOME")"
"$TEST_ROOT/install.sh" --only pi --dry-run >"$TEST_TMP/dry.out"
[ "$before" = "$(tree_fingerprint "$HOME")" ] || fail "--dry-run a modifie le home"
grep -q "^WOULD RENDER $agents$" "$TEST_TMP/dry.out" || fail "--dry-run n'annonce pas AGENTS.md"

if "$TEST_ROOT/install.sh" --only pi --check >"$TEST_TMP/check-agents.out" 2>&1; then
  fail "--check doit detecter une derive d'AGENTS.md"
fi
grep -q "^DRIFT pi $agents content$" "$TEST_TMP/check-agents.out" || fail "derive AGENTS.md mal signalee"
"$TEST_ROOT/install.sh" --only pi >/dev/null

# Une cle retiree de la source disparait de la cible ; une cle de pi reste.
jq '. + {ancienneCle: 1}' "$settings" >"$TEST_TMP/stale"
cat "$TEST_TMP/stale" >"$settings"
jq -c '. + ["ancienneCle"]' "$manifest" >"$TEST_TMP/managed"
cat "$TEST_TMP/managed" >"$manifest"
if "$TEST_ROOT/install.sh" --only pi --check >/dev/null 2>&1; then
  fail "--check doit signaler une cle geree retiree de la source"
fi
"$TEST_ROOT/install.sh" --only pi >/dev/null
[ "$(jq 'has("ancienneCle")' "$settings")" = false ] || fail "cle retiree de la source toujours presente"
[ "$(jq -r .deviceId "$settings")" = abc ] || fail "cle runtime perdue au nettoyage"

# L'ancien manifeste de pi-config sert de manifeste precedent, puis disparait.
jq '. + {ancienneCle: 1}' "$settings" >"$TEST_TMP/stale"
cat "$TEST_TMP/stale" >"$settings"
jq -c '. + ["ancienneCle"]' "$manifest" >"$legacy_manifest"
rm "$manifest"
if "$TEST_ROOT/install.sh" --only pi --check >"$TEST_TMP/check-legacy.out" 2>&1; then
  fail "--check doit signaler l'ancien manifeste"
fi
grep -q "^DRIFT pi $legacy_manifest legacy-manifest$" "$TEST_TMP/check-legacy.out" ||
  fail "ancien manifeste non signale"
"$TEST_ROOT/install.sh" --only pi >"$TEST_TMP/legacy.out"
grep -q "^REMOVE $legacy_manifest$" "$TEST_TMP/legacy.out" || fail "REMOVE de l'ancien manifeste absent"
assert_not_exists "$legacy_manifest"
assert_file "$manifest"
[ "$(jq 'has("ancienneCle")' "$settings")" = false ] || fail "ancien manifeste ignore"
[ "$(jq -r .deviceId "$settings")" = abc ] || fail "cle runtime perdue avec l'ancien manifeste"
"$TEST_ROOT/install.sh" --only pi --check >/dev/null || fail "--check apres reprise de l'ancien manifeste"

# --instructions-only ne touche pas settings.json.
jq '. + {theme: "manuel"}' "$settings" >"$TEST_TMP/theme"
cat "$TEST_TMP/theme" >"$settings"
printf '%s\n' derive >>"$agents"
"$TEST_ROOT/install.sh" --instructions-only --only pi >/dev/null
[ "$(jq -r .theme "$settings")" = manuel ] || fail "--instructions-only a reecrit settings.json"
"$TEST_ROOT/install.sh" --instructions-only --only pi --check >/dev/null || fail "--instructions-only n'a pas rendu AGENTS.md"
"$TEST_ROOT/install.sh" --only pi >/dev/null

# Machine neuve : ni dossier cible ni settings.json. PI_CODING_AGENT_DIR est
# honore, AGENT_CONFIG_PI_DIR le remplace.
PI_CODING_AGENT_DIR="$TEST_TMP/neuf" "$TEST_ROOT/install.sh" --only pi >/dev/null || fail "installation sur machine neuve"
assert_file "$TEST_TMP/neuf/settings.json"
PI_CODING_AGENT_DIR="$TEST_TMP/neuf" "$TEST_ROOT/install.sh" --only pi --check >/dev/null || fail "--check apres installation neuve"
PI_CODING_AGENT_DIR="$TEST_TMP/ignore" AGENT_CONFIG_PI_DIR="$TEST_TMP/prioritaire" \
  "$TEST_ROOT/install.sh" --only pi >/dev/null
assert_file "$TEST_TMP/prioritaire/AGENTS.md"
assert_not_exists "$TEST_TMP/ignore"

if AGENT_CONFIG_PI_DIR=relatif "$TEST_ROOT/install.sh" --only pi --dry-run >"$TEST_TMP/unsafe.out" 2>&1; then
  fail "chemin pi relatif accepte"
fi
grep -q 'unsafe path override: AGENT_CONFIG_PI_DIR=relatif' "$TEST_TMP/unsafe.out" || fail "message de chemin non sur"

# Socle commun absent : l'installation doit echouer.
broken_root="$TEST_TMP/broken-root"
mkdir -p "$broken_root/harnesses"
cp "$TEST_ROOT/install.sh" "$broken_root/install.sh"
cp -R "$TEST_ROOT/harnesses/pi" "$broken_root/harnesses/pi"
if AGENT_CONFIG_PI_DIR="$TEST_TMP/broken-target" \
  "$broken_root/install.sh" --instructions-only --only pi >"$TEST_TMP/broken.out" 2>&1; then
  fail "socle commun absent : l'installation doit echouer"
fi
grep -q 'instructions/common.md' "$TEST_TMP/broken.out" || fail "l'echec ne cite pas le socle commun absent"
assert_not_exists "$TEST_TMP/broken-target/AGENTS.md"

# Ancien manifeste de pi-config : --dry-run annonce son retrait sans y toucher.
legacy_dir="$TEST_TMP/legacy-pi"
mkdir -p "$legacy_dir"
printf '["ancienneCle"]\n' >"$legacy_dir/.pi-config-managed.json"
AGENT_CONFIG_PI_DIR="$legacy_dir" "$TEST_ROOT/install.sh" --only pi --dry-run >"$TEST_TMP/legacy-dry.out"
grep -q "^WOULD REMOVE $legacy_dir/.pi-config-managed.json$" "$TEST_TMP/legacy-dry.out" ||
  fail "--dry-run n'annonce pas le retrait de l'ancien manifeste"
assert_file "$legacy_dir/.pi-config-managed.json"

# Sans aucune extension source, l'installation ne doit pas echouer sur le motif *.ts.
empty_root="$TEST_TMP/empty-ext-root"
mkdir -p "$empty_root"
cp -R "$TEST_ROOT/install.sh" "$TEST_ROOT/instructions" "$TEST_ROOT/harnesses" "$TEST_ROOT/shared" "$TEST_ROOT/upstreams" "$TEST_ROOT/scripts" "$empty_root/" 2>/dev/null || true
rm -f "$empty_root"/harnesses/pi/extensions/*.ts
AGENT_CONFIG_PI_DIR="$TEST_TMP/empty-ext-target" AGENT_CONFIG_SKIP_PLUGINS=1 \
  "$empty_root/install.sh" --only pi >"$TEST_TMP/empty-ext.out" 2>&1 ||
  fail "installation sans extension source : $(tail -2 "$TEST_TMP/empty-ext.out")"

# Fonctions pures de la barre d'etat.
if command -v bun >/dev/null 2>&1; then
  (cd "$TEST_ROOT" && bun test ./tests/pi-statusline.test.ts)
else
  printf '%s\n' 'SKIP: bun absent, tests/pi-statusline.test.ts non execute'
fi

printf 'pi tests: PASS\n'
